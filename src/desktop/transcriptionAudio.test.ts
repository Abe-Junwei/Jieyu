import { it, expect } from 'vitest';
import { pcmWav } from './transcriptionAudio';
it('walks padded RIFF chunks and slices actual PCM frames', () => {
  const bytes = Buffer.alloc(12 + 10 + 24 + 16);
  bytes.write('RIFF');
  bytes.writeUInt32LE(bytes.length - 8, 4);
  bytes.write('WAVE', 8);
  bytes.write('JUNK', 12);
  bytes.writeUInt32LE(1, 16);
  bytes[20] = 99;
  bytes.write('fmt ', 22);
  bytes.writeUInt32LE(16, 26);
  bytes.writeUInt16LE(1, 30);
  bytes.writeUInt16LE(1, 32);
  bytes.writeUInt32LE(4, 34);
  bytes.writeUInt32LE(8, 38);
  bytes.writeUInt16LE(2, 42);
  bytes.writeUInt16LE(16, 44);
  bytes.write('data', 46);
  bytes.writeUInt32LE(8, 50);
  for (let i = 0; i < 4; i++) bytes.writeInt16LE(100 + i, 54 + i * 2);
  const audio = pcmWav(bytes);
  expect(audio.duration).toBe(1);
  const chunk = audio.slice(0.25, 0.75);
  expect(chunk.length).toBe(48);
  expect(chunk.readInt16LE(44)).toBe(101);
  expect(chunk.readInt16LE(46)).toBe(102);
  expect(pcmWav(chunk).duration).toBe(0.5);
  expect(() => pcmWav(bytes.subarray(0, 60))).toThrow('unsupported transcription audio');
});
