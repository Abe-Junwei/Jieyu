#!/usr/bin/env node
/**
 * Generates design/jieyu-paper/preview/icons.js, the Lucide sprite shared by the
 * preview pages, from the installed lucide-react. See DESIGN.md §4.
 *
 *   node scripts/build-od-icon-sprite.mjs          regenerate
 *   node scripts/build-od-icon-sprite.mjs --check  fail if icons.js is stale
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outPath = path.join(root, 'design/jieyu-paper/preview/icons.js');
const lucideDir = path.dirname(createRequire(import.meta.url).resolve('lucide-react/package.json'));
const { version } = createRequire(import.meta.url)('lucide-react/package.json');

// Only names the preview pages actually use; DESIGN.md §4 lists where each one belongs.
const NAMES = [
  'audio-lines',
  'book-open',
  'languages',
  'brain',
  'settings',
  'panel-left-open',
  'play',
  'pause',
  'skip-back',
  'skip-forward',
  'repeat',
  'volume-2',
  'zoom-in',
  'zoom-out',
  'magnet',
  'undo-2',
  'redo-2',
  'upload',
  'file-exclamation-point',
  'copy',
  'search',
  'chevron-down',
  'chevron-right',
  'chevron-up',
  'ellipsis',
  'x',
  'plus',
  'check',
  'grip-vertical',
  'arrow-up',
  'arrow-down',
  'list-indent-decrease',
  'list-indent-increase',
];

const attrs = (o) =>
  Object.entries(o)
    .filter(([k]) => k !== 'key')
    .map(([k, v]) => `${k}="${v}"`)
    .join(' ');

const symbols = [];
for (const name of NAMES) {
  const mod = await import(pathToFileURL(path.join(lucideDir, `dist/esm/icons/${name}.mjs`)).href);
  const body = mod.__iconData.node.map(([tag, a]) => `<${tag} ${attrs(a)}/>`).join('');
  symbols.push(`<symbol id="${name}" viewBox="0 0 24 24">${body}</symbol>`);
}

const sprite = `<svg xmlns="http://www.w3.org/2000/svg" width="0" height="0" style="position:absolute" aria-hidden="true">${symbols.join('')}</svg>`;
const output =
  `// Generated by scripts/build-od-icon-sprite.mjs from lucide-react ${version} (ISC). Do not edit.\n` +
  `// Usage: <svg class="i"><use href="#chevron-down"/></svg>\n` +
  `document.addEventListener('DOMContentLoaded', () => document.body.insertAdjacentHTML('afterbegin', ${JSON.stringify(sprite)}));\n`;

if (process.argv.includes('--check')) {
  if (!existsSync(outPath) || readFileSync(outPath, 'utf8') !== output) {
    console.error(
      '[check:od-icon-sprite] FAIL: preview/icons.js is stale; run npm run build:od-icons',
    );
    process.exit(1);
  }
  console.log('[check:od-icon-sprite] OK');
  process.exit(0);
}

writeFileSync(outPath, output);
console.log(`[build-od-icon-sprite] ${NAMES.length} icons -> ${path.relative(root, outPath)}`);
